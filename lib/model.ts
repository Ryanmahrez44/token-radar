// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol the snapshot records with no token that is not a wrapped, staked or
// bridged product of a token that already trades. The snapshot's watchlist is the floor: all 40 of its
// slugs are ranked, and the early radar adds every other eligible protocol below the floor, so the
// board is the whole launch-candidate universe the snapshot can name, not a top-N by TVL.
//
// Implied value follows only from the snapshot's own figures, the same function for every row:
//
//   base     = tvl_usd x 0.25
//   growth   = clamp(change_7d, -50, 100) per cent
//   growth   = 1 + (growth / 100) x 0.6
//   tenure   = 0.55 + min(age_days, 1460) / 1460 x 0.45   (age_days unknown: 365)
//   chains   = 1 + 0.03 x min(chains - 1, 5)
//   implied  = max(1, round(base x growth x tenure x chains))
//
// TVL is the anchor: a protocol's locked value is the best public proxy for what its token would be
// worth. Seven-day growth moves the score up or down by as much as 60% and -30%. Tenure is the time
// the protocol has run with no token on record, from the day DefiLlama first listed it: a protocol
// that has run four years without a token scores nearly twice a brand-new one, because the longer it
// runs the more the market has priced in a launch that has not happened yet. Chain count is a small
// footprint term: a protocol live on more chains reaches more users. No protocol name is ever
// special-cased, and no row is hand-picked.
//
// A protocol "records no token" when the snapshot carries no market cap, no CoinGecko id and no
// symbol for it. That is the record, never a claim that it has none: a protocol may hold a token its
// DefiLlama record does not carry, and the dashboard says so wherever it shows the status.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

